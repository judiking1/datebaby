/**
 * 특정 월령 및 성별의 백분위수 구간 계산
 */
export function calculatePercentile(gender = "girl", type = "weight", month = 3, value = 6.8) {
  const genderKey = gender === "boy" ? "boy" : "girl";
  const dataset = GROWTH_STANDARDS[genderKey][type];

  // 월령에 가장 가까운 데이터 행 찾기
  let standard = dataset[0];
  for (let i = 0; i < dataset.length; i++) {
    if (dataset[i].month <= month) {
      standard = dataset[i];
    } else {
      break;
    }
  }

  const { p3, p10, p25, p50, p75, p90, p97 } = standard;

  let percentile = 50;
  let statusText = "표준(보통)";
  let statusColor = "text-emerald-600 bg-emerald-50 border-emerald-200";

  if (value < p3) {
    percentile = Math.max(1, Math.round((value / p3) * 3));
    statusText = "체중 관리 필요 (하위 3% 미만)";
    statusColor = "text-rose-600 bg-rose-50 border-rose-200";
  } else if (value < p10) {
    percentile = Math.round(3 + ((value - p3) / (p10 - p3)) * 7);
    statusText = "다소 작은 편 (하위 10%)";
    statusColor = "text-amber-600 bg-amber-50 border-amber-200";
  } else if (value < p25) {
    percentile = Math.round(10 + ((value - p10) / (p25 - p10)) * 15);
    statusText = "평균보다 약간 작음 (하위 25%)";
    statusColor = "text-blue-600 bg-blue-50 border-blue-200";
  } else if (value < p50) {
    percentile = Math.round(25 + ((value - p25) / (p50 - p25)) * 25);
    statusText = "표준 평균 (25~50%)";
    statusColor = "text-emerald-600 bg-emerald-50 border-emerald-200";
  } else if (value < p75) {
    percentile = Math.round(50 + ((value - p50) / (p75 - p50)) * 25);
    statusText = "표준 평균 (50~75%)";
    statusColor = "text-emerald-600 bg-emerald-50 border-emerald-200";
  } else if (value < p90) {
    percentile = Math.round(75 + ((value - p75) / (p90 - p75)) * 15);
    statusText = "평균보다 큰 편 (상위 25%)";
    statusColor = "text-blue-600 bg-blue-50 border-blue-200";
  } else if (value < p97) {
    percentile = Math.round(90 + ((value - p90) / (p97 - p90)) * 7);
    statusText = "매우 큰 편 (상위 10%)";
    statusColor = "text-purple-600 bg-purple-50 border-purple-200";
  } else {
    percentile = Math.min(99, Math.round(97 + ((value - p97) / p97) * 2));
    statusText = "최상위 (상위 3% 이내)";
    statusColor = "text-indigo-600 bg-indigo-50 border-indigo-200";
  }

  return {
    percentile,
    rankFromFront: 100 - percentile + 1, // 100명 중 앞에서 몇 번째
    standard,
    statusText,
    statusColor
  };
}
